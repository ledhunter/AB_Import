/// <summary>
/// Эталонный справочник статей бюджета (Title → Code, КБК) для импорта «Финмодель → ИСР».
///
/// Source: <c>Context/Бюджет_А4.1.xlsx</c> — данные перенесены в статический список ниже
/// (~100 строк). Embed-вариант через ClosedXML отбрасывали: при загрузке xlsx ClosedXML
/// перечисляет системные шрифты, что в тестовой среде не всегда возможно.
///
/// Структура справочника:
///   • колонка A — Code (например <c>"1.1."</c>);
///   • колонка B — Title (наименование статьи).
/// Главы (<c>"1."</c>, <c>"2."</c>, …) и подстатьи в одном плоском списке;
/// родителя восстанавливаем по префиксу Code.
/// </summary>
public interface IBudgetReferenceProvider
{
    /// <summary>Полный плоский список статей справочника в исходном порядке.</summary>
    IReadOnlyList<BudgetReferenceEntry> Entries { get; }

    /// <summary>Найти статью по нормализованному Title (case-insensitive, пробелы свёрнуты).</summary>
    BudgetReferenceEntry? FindByTitle(string title);

    /// <summary>Найти статью по Code (например <c>"1.1."</c>).</summary>
    BudgetReferenceEntry? FindByCode(string code);
}

/// <summary>
/// Одна запись справочника. <see cref="Code"/> хранится в виде
/// <c>"1.1."</c> (с хвостовой точкой — как в Visary). <see cref="Depth"/> — число
/// сегментов перед хвостовой точкой: <c>"1." → 1</c>, <c>"1.1." → 2</c>,
/// <c>"2.2.1.1." → 4</c>. <see cref="ParentCode"/> — Code на уровень выше
/// (для <c>"1.1." → "1."</c>); <c>null</c> у глав.
/// </summary>
public sealed record BudgetReferenceEntry(
    string Code,
    string Title,
    string? ParentCode,
    int Depth,
    bool IsChapter)
{
    /// <summary>Title в нормализованной форме (для матчинга со значениями из Excel).</summary>
    public string NormalizedTitle { get; } = NormalizeTitle(Title);

    public static string NormalizeTitle(string s)
    {
        if (string.IsNullOrWhiteSpace(s)) return string.Empty;
        // Заменяем переводы строк / табы на пробелы, схлопываем пробелы, lower-case.
        var buf = new System.Text.StringBuilder(s.Length);
        bool prevSpace = false;
        foreach (var ch in s)
        {
            char c = ch is '\n' or '\r' or '\t' or ' ' ? ' ' : ch;
            if (c == ' ')
            {
                if (prevSpace) continue;
                prevSpace = true;
            }
            else prevSpace = false;
            buf.Append(char.ToLowerInvariant(c));
        }
        return buf.ToString().Trim();
    }
}

public sealed class BudgetReferenceProvider : IBudgetReferenceProvider
{
    private readonly Lazy<LoadedReference> _loaded;

    public BudgetReferenceProvider(ILogger<BudgetReferenceProvider> log)
    {
        _loaded = new Lazy<LoadedReference>(() => Load(log), isThreadSafe: true);
    }

    public IReadOnlyList<BudgetReferenceEntry> Entries => _loaded.Value.Entries;

    public BudgetReferenceEntry? FindByTitle(string title)
    {
        var key = BudgetReferenceEntry.NormalizeTitle(title);
        return string.IsNullOrEmpty(key) ? null
            : _loaded.Value.ByTitle.TryGetValue(key, out var e) ? e : null;
    }

    public BudgetReferenceEntry? FindByCode(string code)
    {
        var key = NormalizeCode(code);
        return string.IsNullOrEmpty(key) ? null
            : _loaded.Value.ByCode.TryGetValue(key, out var e) ? e : null;
    }

    private static LoadedReference Load(ILogger log)
    {
        var entries = new List<BudgetReferenceEntry>(RawData.Length);
        foreach (var (rawCode, rawTitle) in RawData)
        {
            var code = NormalizeCode(rawCode);
            var title = rawTitle.Trim();
            var depth = code.TrimEnd('.').Split('.').Length;
            var parentCode = depth > 1 ? ParentOf(code) : null;
            var isChapter = depth == 1
                || title.StartsWith("Глава", StringComparison.OrdinalIgnoreCase);
            entries.Add(new BudgetReferenceEntry(code, title, parentCode, depth, isChapter));
        }

        var byCode = entries.ToDictionary(e => e.Code, StringComparer.Ordinal);
        // Title-индекс: при дубликатах Title (разные подстатьи в разных главах с одним
        // именем) берём ПЕРВУЮ — точный матчинг в контексте конкретной главы делается
        // на стороне маппера через ResolveChapterFor.
        var byTitle = new Dictionary<string, BudgetReferenceEntry>(StringComparer.Ordinal);
        foreach (var e in entries)
        {
            if (!byTitle.ContainsKey(e.NormalizedTitle))
                byTitle[e.NormalizedTitle] = e;
        }

        log.LogInformation(
            "BudgetReferenceProvider: loaded {Total} entries ({Chapters} chapters)",
            entries.Count, entries.Count(e => e.IsChapter));
        return new LoadedReference(entries, byCode, byTitle);
    }

    private static string NormalizeCode(string raw)
    {
        var s = raw?.Trim() ?? string.Empty;
        if (s.Length == 0) return s;
        return s.EndsWith('.') ? s : s + ".";
    }

    private static string ParentOf(string code)
    {
        // "1.1." → "1.";  "2.2.1.1." → "2.2.1."
        var trimmed = code.TrimEnd('.');
        var idx = trimmed.LastIndexOf('.');
        return idx < 0 ? code : trimmed[..(idx + 1)];
    }

    private sealed record LoadedReference(
        IReadOnlyList<BudgetReferenceEntry> Entries,
        IReadOnlyDictionary<string, BudgetReferenceEntry> ByCode,
        IReadOnlyDictionary<string, BudgetReferenceEntry> ByTitle);

